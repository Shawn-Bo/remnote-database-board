const assert = require('node:assert/strict');
const fs = require('node:fs');
const path = require('node:path');
// Isolated synthetic fixture only. Start it with BOARD_PORT=8083 npm run serve.
const {webkit} = require(process.env.BOARD_PLAYWRIGHT_MODULE || 'playwright');
const fixture = require('../src/demo-snapshot.json');
const config = require('../src/demo-config.json');
const output = path.resolve(process.env.BOARD_TEST_OUTPUT || './test-output');
async function main() {
  fs.mkdirSync(output, {recursive:true});
  const browser = await webkit.launch({headless:true});
  const context = await browser.newContext({viewport:{width:1500,height:940}});
  const page = await context.newPage();
  const errors = [], checks = [];
  page.on('pageerror', e => errors.push(e.message));
  await page.route('**/*', route => new URL(route.request().url()).hostname === 'localhost' ? route.continue() : route.abort());
  const saved = () => page.evaluate(() => JSON.parse(sessionStorage.getItem('remnote-board-preview:v1')));
  const waitCell = (rowId, field, value) => page.waitForFunction(({rowId,field,value}) => {
    const cell = JSON.parse(sessionStorage.getItem('remnote-board-preview:v1'))?.rows.find(r => r.id === rowId)?.cells[field];
    return cell && (cell.refs[0] === value || cell.text === value);
  }, {rowId,field,value});
  try {
    await page.goto(process.env.BOARD_TEST_URL || 'http://localhost:8083/preview.html');
    await page.waitForSelector('.card');
    assert.equal(await page.locator('.card').count(),9);
    assert.equal(await page.locator('.column').count(),9);
    await page.screenshot({path:path.join(output,'preview-initial.png')});
    const rowId = fixture.rows[0].id, target = fixture.fields[1].choices[1].id;
    const origin = await page.locator(`[data-row-id="${rowId}"] .grip`).boundingBox();
    const destination = await page.locator(`[data-column-id="${target}"] .column-heading`).boundingBox();
    const drag = async () => {
      await page.mouse.move(origin.x + origin.width/2, origin.y + origin.height/2);
      await page.mouse.down();
      await page.mouse.move(destination.x + destination.width/2, destination.y + destination.height/2,{steps:12});
    };
    await drag();
    await page.keyboard.press('Escape');
    await page.mouse.up();
    assert.equal(await saved(),null);
    assert.equal(await page.locator('.card.dragging').count(),0);
    checks.push('Escape cancels a pointer drag without changing records');
    await drag();
    await page.mouse.up();
    await waitCell(rowId,config.groupFieldId,target);
    assert.equal(await page.locator(`[data-column-id="${target}"] .card`).count(),2);
    const changed = (await saved()).rows.find(r => r.id === rowId);
    assert.equal(changed.parentId,fixture.rows[0].parentId);
    for (const [id,cell] of Object.entries(fixture.rows[0].cells)) if (id !== config.groupFieldId) assert.deepEqual(changed.cells[id],cell);
    checks.push('Drag changes only the selected grouping property');
    await page.getByRole('tab',{name:'表格',exact:true}).click();
    const row = page.locator(`tr[data-row-id="${rowId}"]`);
    assert.equal(await row.getByLabel(fixture.fields.find(f => f.id === config.groupFieldId).name,{exact:true}).inputValue(),target);
    await row.getByRole('button',{name:'编辑进展记录',exact:true}).click();
    await row.getByRole('textbox',{name:'编辑进展记录',exact:true}).fill('示例练习记录');
    await row.getByRole('textbox',{name:'编辑进展记录',exact:true}).press('Enter');
    await waitCell(rowId,config.recordFieldId,'示例练习记录');
    checks.push('Table edits an original property without a copied note-body editor');
    await page.getByRole('button',{name:'筛选',exact:true}).click();
    await page.getByRole('button',{name:'添加筛选条件',exact:true}).click();
    await page.getByLabel('筛选属性 1',{exact:true}).selectOption(config.filterFieldId);
    await page.getByLabel('筛选值 1',{exact:true}).selectOption('example-option-1-2');
    await page.getByRole('button',{name:'排序',exact:true}).click();
    await page.getByRole('button',{name:'添加排序',exact:true}).click();
    await page.getByLabel('排序方向 1',{exact:true}).selectOption('desc');
    await page.getByRole('button',{name:'关闭设置',exact:true}).click();
    const expected = ['example-row-08','example-row-05','example-row-02'];
    assert.deepEqual(await page.locator('tbody tr').evaluateAll(rows => rows.map(r => r.dataset.rowId)),expected);
    await page.reload();
    await page.waitForSelector('tbody tr');
    assert.deepEqual(await page.locator('tbody tr').evaluateAll(rows => rows.map(r => r.dataset.rowId)),expected);
    checks.push('Per-view filter and descending sort survive reload');
    await page.getByRole('tab',{name:'看板',exact:true}).click();
    assert.equal(await page.locator('.card').count(),9);
    assert.match(await page.locator(`[data-row-id="${rowId}"] .card-preview`).innerText(),/示例练习记录/);
    await page.locator(`[data-row-id="${rowId}"] .card-title`).click();
    assert.equal(await page.getByRole('button',{name:'在 RemNote 打开完整笔记',exact:true}).count(),2);
    assert.equal(await page.locator('textarea').count(),0);
    await page.getByRole('button',{name:'关闭笔记',exact:true}).click();
    checks.push('Board keeps its own query and opens the original-note entry');
    assert.deepEqual(errors,[]);
    fs.writeFileSync(path.join(output,'browser-test-result.json'),JSON.stringify({passed:true,engine:'WebKit; synthetic fixture only; native RemNote editor not included',checks,pageErrors:errors},null,2));
    console.log(JSON.stringify({passed:true,checks,pageErrors:errors},null,2));
  } finally {await browser.close();}
}
main().catch(e => {console.error(e);process.exitCode=1;});
