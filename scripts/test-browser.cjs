const assert = require('node:assert/strict');
const fs = require('node:fs');
const path = require('node:path');
// Runs only against this project's isolated fixture, never the user's app/browser.
const {webkit} = require(process.env.BOARD_PLAYWRIGHT_MODULE || 'playwright');
const fixture = require('../src/demo-snapshot.json');
const config = require('../src/demo-config.json');
const output = path.resolve(process.env.BOARD_TEST_OUTPUT || './test-output');
async function main(){
  fs.mkdirSync(output,{recursive:true});
  const browser=await webkit.launch({headless:true});
  const context=await browser.newContext({viewport:{width:1500,height:940}});
  const page=await context.newPage();
  const errors=[], checks=[];
  page.on('pageerror',e=>errors.push(e.message));
  await page.route('**/*',route=>new URL(route.request().url()).hostname==='localhost'?route.continue():route.abort());
  const saved=async()=>page.evaluate(()=>JSON.parse(sessionStorage.getItem('remnote-board-preview:v1')));
  try{
    await page.goto(process.env.BOARD_TEST_URL || 'http://localhost:8081/preview.html');
    await page.waitForSelector('.card');
    assert.equal(await page.locator('.card').count(),9);assert.equal(await page.locator('.column').count(),9);
    checks.push('Nine original option columns and nine unique cards');
    await page.screenshot({path:path.join(output,'preview-initial.png')});
    const rowId=fixture.rows[0].id, target=fixture.fields[1].choices[1].id;
    const origin = await page.locator(`[data-row-id="${rowId}"] .grip`).boundingBox();
    const destination = await page.locator(`[data-column-id="${target}"] .column-heading`).boundingBox();
    await page.mouse.move(origin.x + origin.width/2, origin.y + origin.height/2);
    await page.mouse.down();
    await page.mouse.move(destination.x + destination.width/2, destination.y + destination.height/2,{steps:12});
    await page.keyboard.press('Escape');
    await page.mouse.up();
    assert.equal((await saved())?.rows[0].cells[config.groupFieldId].refs[0] ?? fixture.rows[0].cells[config.groupFieldId].refs[0],fixture.rows[0].cells[config.groupFieldId].refs[0]);
    assert.equal(await page.locator('.card.dragging').count(),0);
    checks.push('Escape cancels pointer drag without writing');
    await page.mouse.move(origin.x + origin.width/2, origin.y + origin.height/2);
    await page.mouse.down();
    await page.mouse.move(destination.x + destination.width/2, destination.y + destination.height/2,{steps:12});
    await page.mouse.up();
    await page.waitForFunction(({rowId,target,field})=>{const data=JSON.parse(sessionStorage.getItem('remnote-board-preview:v1'));return data?.rows.find(r=>r.id===rowId)?.cells[field].refs[0]===target;},{rowId,target,field:config.groupFieldId});
    assert.equal(await page.locator(`[data-column-id="${target}"] .card`).count(),2);
    const afterDrag=await saved();
    assert.equal(afterDrag.rows[0].id,fixture.rows[0].id);assert.equal(afterDrag.rows[0].parentId,fixture.rows[0].parentId);
    assert.deepEqual(afterDrag.rows[0].cells[config.recordFieldId],fixture.rows[0].cells[config.recordFieldId]);
    checks.push('Real pointer drag updates destination and preserves row ID, parent and training record in fixture');
    await page.getByRole('button',{name:'☷ 表格',exact:true}).click();
    assert.equal(await page.locator('tbody tr').count(),9);
    assert.equal(await page.getByLabel(`${fixture.rows[0].name}的熟练度`,{exact:true}).inputValue(),target);
    checks.push('Table view reflects the same changed row');
    await page.getByRole('button',{name:'▥ 看板',exact:true}).click();
    await page.getByLabel('筛选歌曲',{exact:true}).selectOption('歌曲 B');
    assert.equal(await page.locator('.card').count(),3);
    await page.getByLabel('搜索分段',{exact:true}).fill('示例分段 05');assert.equal(await page.locator('.card').count(),1);
    await page.getByLabel('搜索分段',{exact:true}).fill('');await page.getByLabel('筛选歌曲',{exact:true}).selectOption('*');
    checks.push('Song filter and full-text search combine without moving records');
    await page.locator(`[data-row-id="${rowId}"] .card-title`).click();
    await page.getByLabel('进展记录',{exact:true}).fill('2026-10-29\n示例练习记录。');
    await page.screenshot({path:path.join(output,'preview-record.png')});
    await page.getByRole('button',{name:'保存记录',exact:true}).click();
    await page.waitForFunction(({rowId,field})=>JSON.parse(sessionStorage.getItem('remnote-board-preview:v1'))?.rows.find(r=>r.id===rowId)?.cells[field].text.includes('示例练习记录'),{rowId,field:config.recordFieldId});
    assert.deepEqual((await saved()).rows[0].cells[config.groupFieldId].refs,[target]);
    checks.push('Progress save modifies only text field, preserving proficiency');
    await page.reload();await page.waitForSelector('.card');
    assert.match(await page.locator(`[data-row-id="${rowId}"] .card-preview`).innerText(),/示例练习记录/);
    assert.equal(await page.locator(`[data-column-id="${target}"] .card`).count(),2);
    checks.push('Fixture reload retains saved group and progress');
    await page.getByLabel(`${fixture.rows[0].name}的熟练度`,{exact:true}).selectOption('__empty__');
    await page.waitForSelector(`[data-column-id="__empty__"] [data-row-id="${rowId}"]`);
    checks.push('Clear proficiency reveals unassigned column without losing the card');
    await page.setViewportSize({width:390,height:844});
    assert.equal(await page.locator('.card').count(),9);
    await page.getByLabel(`${fixture.rows[0].name}的熟练度`,{exact:true}).selectOption(target);
    await page.waitForFunction(({rowId,target,field})=>JSON.parse(sessionStorage.getItem('remnote-board-preview:v1'))?.rows.find(r=>r.id===rowId)?.cells[field].refs[0]===target,{rowId,target,field:config.groupFieldId});
    await page.screenshot({path:path.join(output,'preview-mobile.png')});
    checks.push('Narrow viewport proficiency selection works without drag');
    assert.deepEqual(errors,[]);
    fs.writeFileSync(path.join(output,'browser-test-result.json'),JSON.stringify({passed:true,engine:'Playwright WebKit; isolated local fixture only',checks,pageErrors:errors},null,2));
    console.log(JSON.stringify({passed:true,checks:checks.length,pageErrors:errors,screenshots:output},null,2));
  } finally {await browser.close();}
}
main().catch(e=>{console.error(e);process.exitCode=1;});
